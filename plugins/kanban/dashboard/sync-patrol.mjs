/** Build-time seam only: embed the native plugin's pure projector in the no-build dashboard. */
import { readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'

const source = new URL('../../../apps/desktop/src/plugins/kanban/patrol-model.ts', import.meta.url)
const target = new URL('./dist/index.js', import.meta.url)
const js = ts.transpileModule(readFileSync(source, 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS }
}).outputText
const generated = `  // BEGIN GENERATED PATROL MODEL\n  // Generated by node plugins/kanban/dashboard/sync-patrol.mjs; edit patrol-model.ts.\n  const patrolModel = (function () {\n    const exports = {};\n${js}\n    return exports;\n  })();\n  // END GENERATED PATROL MODEL`
const before = readFileSync(target, 'utf8')
const after = before.replace(/  \/\/ BEGIN GENERATED PATROL MODEL[\s\S]*?  \/\/ END GENERATED PATROL MODEL/, generated)
if (process.argv.includes('--check')) {
  if (before !== after) throw new Error('Dashboard patrol model is stale; run sync-patrol.mjs')
} else writeFileSync(target, after)
